          ),
        ),
        const Divider(height: 1),
        Expanded(child: SingleChildScrollView(padding: const EdgeInsets.all(16), child: SelectableText(_script.isEmpty ? '暂无配音脚本，保存说课内容后将自动生成。' : _script, style: TextStyle(fontSize: 14, height: 1.8, color: textColor)))),
      ],
    );
  }

