  Widget _buildVideoEditor() {
    return Container(padding: const EdgeInsets.fromLTRB(12, 0, 12, 12), child: Column(crossAxisAlignment: CrossAxisAlignment.start, mainAxisSize: MainAxisSize.min, children: [
      Row(children: [const Icon(Icons.video_library_outlined, size: 18), const SizedBox(width: 6), const Text('视频演示', style: TextStyle(fontWeight: FontWeight.w600)), const Spacer(), TextButton.icon(icon: const Icon(Icons.add, size: 18), label: const Text('添加视频'), onPressed: _addVideo)]),
