  String _stripMarkdown(String md) {
    var text = md;
    text = text.replaceAll(RegExp(r'```[\s\S]*?```'), '');
    text = text.replaceAll(RegExp(r'`[^`]+`'), '');
    text = text.replaceAll(RegExp(r'!\[([^\]]*)\]\([^)]+\)'), '');
    text = text.replaceAll(RegExp(r'\[([^\]]+)\]\([^)]+\)'), r'$1');
    text = text.replaceAll(RegExp(r'[*_]{1,3}'), '');
    text = text.replaceAll(RegExp(r'^#{1,6}\s+', multiLine: true), '');
    text = text.replaceAll(RegExp(r'^[-*_]{3,}\s*$', multiLine: true), '');
    text = text.replaceAll(RegExp(r'\|'), ' ');
    text = text.replaceAll(RegExp(r'^[-:\s|]+$', multiLine: true), '');
    text = text.replaceAll(RegExp(r'^[-*+]\s+', multiLine: true), '');
    text = text.replaceAll(RegExp(r'^\d+\.\s+', multiLine: true), '');
    text = text.replaceAll(RegExp(r'\n{3,}'), '\n\n');
    return text.trim();
  }

  List<String> _parseVideoUrls(dynamic value) {
    final urls = <String>[];
    if (value != null) {
      try { urls.addAll(List<String>.from(jsonDecode(value as String))); } catch (_) {}
    }
    return urls;
  }

  Future<void> _saveToDb(String content, List<String> urls) async {
    try {
      final db = await DatabaseHelper.instance.database;
      final rows = await db.query('lecture_notes', where: 'course_id = ?', whereArgs: ['default'], limit: 1);
      final data = {'content': content, 'video_urls': jsonEncode(urls), 'script': _script, 'updated_at': DateTime.now().toIso8601String()};
      if (rows.isEmpty) {
        await db.insert('lecture_notes', {'course_id': 'default', 'title': '说课', ...data});
      } else {
        await db.update('lecture_notes', data, where: 'course_id = ?', whereArgs: ['default']);
      }
    } catch (_) {}
  }

  Future<void> _saveContent() async {
    _content = _editCtrl.text; _generateScript();
    try {
      final db = await DatabaseHelper.instance.database;
      await db.update('lecture_notes', {'content': _content, 'video_urls': jsonEncode(_videoUrls), 'script': _script, 'updated_at': DateTime.now().toIso8601String()}, where: 'course_id = ?', whereArgs: ['default']);
      if (mounted) { ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('说课内容已保存'))); setState(() => _isEditing = false); }
    } catch (e) { if (mounted) { ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('保存失败: $e'), backgroundColor: Colors.red)); } }
  }

  Future<void> _importFromFile() async {
    try {
      final result = await FilePicker.platform.pickFiles(type: FileType.custom, allowedExtensions: ['md', 'markdown', 'txt']);
      if (result == null || result.files.isEmpty) return;
      final file = File(result.files.single.path!);
      final imported = await file.readAsString();
      _editCtrl.text = imported; _content = imported; _generateScript();
      if (mounted) { setState(() {}); ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('文件已导入'))); }
    } catch (e) { if (mounted) { ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('导入失败: $e'), backgroundColor: Colors.red)); } }
  }

  Future<void> _addVideo() async {
    final result = await FilePicker.platform.pickFiles(type: FileType.custom, allowedExtensions: ['mp4', 'avi', 'mkv', 'mov', 'wmv', 'flv']);
    if (result == null || result.files.isEmpty) return;
    final path = result.files.single.path; if (path == null) return;
    if (!mounted) return; setState(() => _videoUrls.add(path)); _saveVideoUrls();
  }

  void _removeVideo(int index) { setState(() => _videoUrls.removeAt(index)); _saveVideoUrls(); }

  Future<void> _saveVideoUrls() async {
    try {
      final db = await DatabaseHelper.instance.database;
      await db.update('lecture_notes', {'video_urls': jsonEncode(_videoUrls), 'updated_at': DateTime.now().toIso8601String()}, where: 'course_id = ?', whereArgs: ['default']);
    } catch (_) {}
  }

  Future<void> _saveScript() async {
    try {
      final db = await DatabaseHelper.instance.database;
      await db.update('lecture_notes', {'script': _script, 'updated_at': DateTime.now().toIso8601String()}, where: 'course_id = ?', whereArgs: ['default']);
    } catch (_) {}
  }

  Future<void> _speakContent() async {
    final tts = TtsFlutterService.instance;
    if (_isSpeaking) { await tts.stop(); if (mounted) setState(() => _isSpeaking = false); return; }
    final text = _script.isNotEmpty ? _script : _stripMarkdown(_content);
    if (text.isEmpty) return; setState(() => _isSpeaking = true);
    await tts.speak(text); if (mounted) setState(() => _isSpeaking = false);
  }

  void _openVideo(String path) {
    if (!Platform.isWindows && !Platform.isLinux && !Platform.isMacOS) return;
    Navigator.push(context, MaterialPageRoute(builder: (_) => InAppVideoPlayerPage(filePath: path, title: path.split(Platform.pathSeparator).last, chapter: '说课')));
  }

  void _openCoursewareWorkshop() {
    Navigator.push(context, MaterialPageRoute(builder: (_) => const CoursewareWorkshopPage()));
  }

  Future<void> _exportPdf() async {
    try {
      final pdfBytes = await NativePdfService.instance.markdownToPdf(_content);
      final outDir = await _ensureExportDir();
      final path = '$outDir说课_$_courseName.pdf';
      await File(path).writeAsBytes(pdfBytes);
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('PDF 已导出: $path'), backgroundColor: Colors.green));
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('PDF 导出失败: $e'), backgroundColor: Colors.red));
    }
  }

  Future<String> _ensureExportDir() async {
    final dirs = ['$_dataDir/说课/', '$_dataDir/视频/'];
    for (final d in dirs) {
      final dir = Directory(d);
      if (!dir.existsSync()) await dir.create(recursive: true);
    }
    return dirs[0];
  }

  Future<void> _generateLectureVideo() async {
    setState(() { _generating = true; _genStatus = '正在准备视频生成...'; });

    try {
      final script = _script.isNotEmpty ? _script : _stripMarkdown(_content);
      final paragraphs = script.split('\n').where((l) => l.trim().isNotEmpty).toList();
      final outDir = '$_dataDir说课/';
      Directory(outDir).createSync(recursive: true);

      setState(() => _genStatus = '正在生成语音...');
      final ttsService = TtsService();
      final audioDir = '${outDir}audio/';
      Directory(audioDir).createSync(recursive: true);
      final audios = <String>[];
      final narrations = <Map<String, String>>[];

      for (var i = 0; i < paragraphs.length; i++) {
        narrations.add({'narration': paragraphs[i], 'voice': 'zh-CN-XiaoxiaoNeural', 'rate': '+0%'});
      }

      await ttsService.generateBatchAudio(scripts: narrations, outputDir: audioDir, onProgress: (current, total) {
        setState(() => _genStatus = '正在生成语音... $current/$total');
      });

      for (var i = 0; i < paragraphs.length; i++) {
        final audioPath = '${audioDir}slide_${i.toString().padLeft(3, '0')}.mp3';
        if (await File(audioPath).exists()) audios.add(audioPath);
      }

      setState(() => _genStatus = '正在生成视频...');
      final videoService = VideoService();
      final screenshots = Directory('assets/help/archievement').existsSync()
          ? Directory('assets/help/archievement').listSync().whereType<File>().map((f) => f.path).where((p) => p.endsWith('.png')).take(audios.length).toList()
          : <String>[];

      final slides = <String>[];
      if (screenshots.isNotEmpty) {
        for (var i = 0; i < audios.length; i++) {
          slides.add(screenshots[i % screenshots.length]);
        }
      } else {
        slides.addAll(List.filled(audios.length, ''));
      }

      final videoPath = '$outDir说课演示_$_courseName.mp4';
      final success = await videoService.generateVideo(
        slides: slides,
        audios: audios,
        outputPath: videoPath,
        onProgress: (c, t, m) => setState(() => _genStatus = m),
      );

      if (success && await File(videoPath).exists()) {
        setState(() { _videoUrls.add(videoPath); _generating = false; _genStatus = ''; });
        _saveVideoUrls();
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('视频已生成: $videoPath'), backgroundColor: Colors.green));
          _openVideo(videoPath);
        }
      } else {
        setState(() { _generating = false; _genStatus = '视频生成失败'; });
        if (mounted) ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('视频生成失败，请检查 TTS/FFmpeg 是否可用'), backgroundColor: Colors.red));
      }
    } catch (e) {
      setState(() { _generating = false; _genStatus = '生成出错'; });
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('生成出错: $e'), backgroundColor: Colors.red));
    }
  }

  @override
  Widget build(BuildContext context) {
    final isPrint = AppGradientTheme.isPrint(context);
    final bgColor = isPrint ? Colors.white : Theme.of(context).scaffoldBackgroundColor;
    final textColor = isPrint ? Colors.black87 : (Theme.of(context).brightness == Brightness.dark ? Colors.white : Colors.black87);
    final accentColor = Theme.of(context).colorScheme.primary;

    return Scaffold(
      backgroundColor: bgColor,
      appBar: AppBar(
        backgroundColor: isPrint ? Colors.white : null,
        title: Text('说课', style: TextStyle(color: isPrint ? Colors.black87 : null)),
        iconTheme: IconThemeData(color: isPrint ? Colors.black87 : null),
        actions: _isEditing
            ? [
                IconButton(icon: const Icon(Icons.undo), tooltip: '取消编辑', onPressed: () { _editCtrl.text = _content; setState(() => _isEditing = false); }),
                IconButton(icon: const Icon(Icons.save_outlined), tooltip: '保存', onPressed: _saveContent),
              ]
            : [
                IconButton(icon: Icon(_isSpeaking ? Icons.stop_circle_outlined : Icons.volume_up_outlined), tooltip: _isSpeaking ? '停止播报' : '语音播报', onPressed: _isLoading ? null : _speakContent),
                if (_videoUrls.isNotEmpty && (Platform.isWindows || Platform.isLinux || Platform.isMacOS))
                  PopupMenuButton<String>(icon: const Icon(Icons.video_library_outlined), tooltip: '视频演示',
                    onSelected: (path) => _openVideo(path),
                    itemBuilder: (_) => _videoUrls.map((path) => PopupMenuItem(value: path, child: Text(path.split(Platform.pathSeparator).last, overflow: TextOverflow.ellipsis))).toList()),
                IconButton(icon: Icon(Icons.record_voice_over_outlined, color: _script.isNotEmpty ? accentColor : null), tooltip: '配音脚本', onPressed: _isLoading ? null : () => setState(() => _showScript = !_showScript)),
                IconButton(icon: const Icon(Icons.picture_as_pdf_outlined), tooltip: '导出 PDF', onPressed: _isLoading ? null : _exportPdf),
                IconButton(icon: const Icon(Icons.smart_display_outlined), tooltip: '课件工坊', onPressed: _isLoading ? null : _openCoursewareWorkshop),
                IconButton(icon: const Icon(Icons.edit_outlined), tooltip: '编辑', onPressed: _isLoading ? null : () => setState(() => _isEditing = true)),
                IconButton(icon: const Icon(Icons.file_upload_outlined), tooltip: '导入 .md', onPressed: _isLoading ? null : () async { await _importFromFile(); if (_isEditing == false) setState(() => _isEditing = true); }),
                IconButton(icon: const Icon(Icons.copy), tooltip: '复制内容', onPressed: _isLoading ? null : () => ClipboardHelper.copyWithToast(context, _content)),
              ],
      ),
      body: _isLoading
          ? const Center(child: CircularProgressIndicator())
          : _generating
              ? _buildGenerationProgress()
              : _isEditing
                  ? _buildEditor(textColor)
                  : _showScript
                      ? _buildScriptView(isPrint)
                      : _buildPreview(isPrint),
    );
  }

  Widget _buildGenerationProgress() {
    return Center(
